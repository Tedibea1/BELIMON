const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const ctx={window:{},Math};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(__dirname+'/../js/combat.js','utf8'),ctx);
const C=ctx.window.TDWCombat;
let checks=0;const eq=(x,y,label)=>{assert.deepEqual(JSON.parse(JSON.stringify(x)),y,label);checks++;};
const ok=(x,label)=>{assert.ok(x,label);checks++;};
const gen=(classId,stats={force:20,rapidite:0,constitution:0},hp=400,energy=100)=>({classId,stats,maxHp:hp,hp,energy});
const rng=(...a)=>{let i=0;return ()=>a[i++]??.99;};
const zero=()=>.99;
eq(C.COST,{light:2,heavy:3,special:5,defend:0,idle:0},'cost');
eq(Object.keys(C.SPECIALS).length,6,'six specials');
eq(C.combatChances({rapidite:1000}),{dodge:30,critical:30},'caps');
eq(C.combatStats({stats:{force:20,rapidite:10,constitution:15}},{force:2,rapidite:3,constitution:4}),{force:24,rapidite:16,constitution:23},'flat global bonuses');
const e=gen('epeiste'),p=gen('epeiste');
eq(C.chooseEnemyAction(100,()=>.99,e,1),'defend','AI defense');
eq(C.chooseEnemyAction(100,()=>.7,e,1),'special','AI special');
eq(C.chooseEnemyAction(0,()=>0,e,1),'defend','AI cannot overspend');
for(const type of ['epeiste','bagarreuse','archere_arcanique','occultiste','pretresse','griffeuse']){
 const hero=gen(type,{force:20,rapidite:0,constitution:0});
 const result=C.resolveTurn(hero,gen('griffeuse'), 'special',{},rng(.99,.99,.99,.99,.99,.99,.99),{turn:1});
 eq(result.player.energy,95,`${type}: special -5`);
 ok(result.summary.includes(C.SPECIALS[type].name),`${type}: special name`);
}
const noAI=gen('bagarreuse',{},400,0);
const arch=C.resolveTurn(gen('archere_arcanique'),noAI,'special',{},zero,{turn:1});
eq(arch.details.player.damage,17,'arcane 1.7 versus defense');
const claw=C.resolveTurn(gen('griffeuse'),noAI,'special',{},zero,{turn:1});
eq(claw.details.player.damage,30,'claw forced critical 1.0×3 versus defense');
const sword=C.resolveTurn(gen('epeiste'),noAI,'special',{},zero,{turn:1});
eq(sword.details.player.damage,14,'sword 1.4 versus defense');
eq(sword.effects.enemy.swordCons,true,'sword constitution debuff');
const swordAgain=C.resolveTurn(gen('epeiste'),noAI,'special',{},zero,{turn:2,effects:sword.effects});
eq(swordAgain.effects.enemy.swordCons,true,'sword nonstacking');
eq(C.penaltyFor(swordAgain.effects.enemy,2).constitution,.15,'sword penalty');
const priest=gen('pretresse',{},100);priest.hp=30;
const bless=C.resolveTurn(priest,noAI,'special',{},zero,{turn:1});
eq(bless.player.hp,70,'heal 40%');
const priest2=gen('pretresse',{},100);priest2.hp=90;
eq(C.resolveTurn(priest2,noAI,'special',{},zero,{turn:1}).player.hp,100,'heal capped');
eq(C.chooseEnemyAction(100,()=>0.1,priest,1),'special','priest AI prioritizes healing');
const occult=gen('occultiste');let effect;
const curse=C.resolveTurn(occult,noAI,'special',{},zero,{turn:1});
effect=curse.effects;
eq(effect.enemy.curse.expiresTurn,5,'curse initially lasts five turns');
eq(effect.enemy.curse.percent,0,'curse begins at 0 percent until first second');
for(const turn of [2,3,4,5,6])eq(C.canUseSpecial(occult,100,turn,effect.player),true,`curse cooldown removed, turn ${turn}`);
const target={...gen('bagarreuse'),energy:100};
const first=C.tickTimedEffects(effect,occult,target,1000,2);
effect=first.effects;
eq(effect.enemy.curse.nextTickAt,2000,'curse clock armed after one second');
const tick=C.tickTimedEffects(effect,occult,target,2000,2);
effect=tick.effects;
eq(effect.enemy.curse.percent,2,'curse −2 %/s');
eq(C.penaltyFor(effect.enemy,2).force,.02,'curse penalty applied to stats');
const renewed=C.resolveTurn(occult,noAI,'special',{},zero,{turn:2,effects:effect});
eq(renewed.effects.enemy.curse.expiresTurn,6,'curse refreshes five turns');
eq(renewed.effects.enemy.curse.percent,2,'curse preserves accumulated percentage');
eq(renewed.effects.enemy.curse.nextTickAt,3000,'curse preserves current second cadence');
effect=renewed.effects;
for(let turn=3;turn<=6;turn++){
 const res=C.resolveTurn(occult,noAI,'defend',{},zero,{turn,effects:effect});effect=res.effects;
}
eq(effect.enemy.curse,null,'curse expires after five tours from refresh');
const siphon=C.resolveTurn(gen('bagarreuse'),noAI,'special',{},zero,{turn:3});
eq(siphon.effects.enemy.siphon.expiresTurn,6,'four turns inclusive');
const renew=C.resolveTurn(gen('bagarreuse'),noAI,'special',{},zero,{turn:4,effects:siphon.effects});
eq(renew.effects.enemy.siphon.expiresTurn,7,'siphon renew instead of stack');
const skipped=C.resolveTurn(gen('epeiste'),gen('bagarreuse'),'idle',{},rng(0),{turn:1});
eq(skipped.player.energy,100,'timeout no energy cost');
ok(skipped.player.hp<400,'timeout enemy retaliates');
const oneHit=C.resolveTurn(gen('archere_arcanique',{force:1000,rapidite:0,constitution:0}),{...gen('bagarreuse'),hp:1},'special',{},zero,{turn:1});
eq(oneHit.result,'won','kill');
eq(oneHit.enemy.energy,100,'KO cancels AI energy consumption');
console.log('✅ V3.1 combat rules:',checks,'tests passed');
