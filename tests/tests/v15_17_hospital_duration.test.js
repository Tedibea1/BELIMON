'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const root=path.join(__dirname,'../..');
const ctx={window:{},Date,Math};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'js/hospital.js'),'utf8'),ctx,{filename:'hospital.js'});
const H=ctx.window.BellymonHospital;
let checks=0;
const eq=(got,want,message)=>{assert.equal(got,want,message);checks++};
const patient=(id,hp,maxHp=100)=>({id,hp,maxHp,energy:0,injuredUntil:0});
const state=(heroes)=>({tower:{floor:1,event:{state:'rest'}},waifus:heroes,hospital:{slots:[]}});
eq(H.CAPACITY,3,'three hospital beds');
eq(H.HEAL_MS,18000,'18 seconds max unchanged');
for(const [hp,ms] of [[0,18000],[25,13500],[50,9000],[75,4500],[100,0]]){
 eq(H.healDurationMs(patient('test',hp)),ms,Math.abs(100-hp)+'% missing HP');
}
eq(H.healDurationMs(patient('test',1,68)),17735,'proportional timing supports different maxHP');
eq(H.healDurationMs(patient('test',67,68)),265,'very small injury shorter');
eq(H.healDurationMs(patient('test',-5)),18000,'duration capped on invalid negative HP');
eq(H.healDurationMs(patient('test',110)),0,'no negative duration');
const data=state([patient('ko',0),patient('75missing',25),patient('25missing',75),patient('fourth',50)]);
const startAt=1_000_000;
eq(H.start(data,'ko',startAt),startAt+18000,'KO 18 seconds');
eq(H.start(data,'75missing',startAt),startAt+13500,'25/100HP 13.5 seconds');
eq(H.start(data,'25missing',startAt),startAt+4500,'75/100HP 4.5 seconds');
eq(data.hospital.slots.length,3,'all three beds used');
assert.throws(()=>H.start(data,'fourth',startAt),/trois lits/);checks++;
eq(H.complete(data,startAt+4499),0,'nothing before first deadline');
eq(H.complete(data,startAt+4500),1,'short treatment finishes independently');
eq(data.waifus[2].hp,100,'short treatment restores full HP');
eq(data.waifus[2].energy,100,'short treatment restores energy');
eq(data.hospital.slots.length,2,'short treatment frees a bed');
eq(H.start(data,'fourth',startAt+5000),startAt+14000,'freed bed can take next patient');
const restored=JSON.parse(JSON.stringify(data));
eq(H.complete(restored,startAt+13499),0,'longer treatments remain pending after reload');
eq(H.complete(restored,startAt+13500),1,'13.5 seconds completes at exact deadline');
eq(H.complete(restored,startAt+14000),1,'new patient finishes at own deadline');
eq(H.complete(restored,startAt+18000),1,'KO finishes at 18 seconds');
eq(restored.hospital.slots.length,0,'all beds freed at their own due dates');
assert.throws(()=>H.start(restored,'ko',startAt+19000),/tous ses PV/);checks++;
const upper=state([patient('upper',0)]);upper.tower.floor=2;
assert.throws(()=>H.start(upper,'upper',0),/étage 1/);checks++;
const ongoing=state([patient('legacy',0)]);ongoing.hospital.slots.push({heroId:'legacy',readyAt:30_000});ongoing.waifus[0].injuredUntil=30_000;
eq(H.complete(ongoing,29_999),0,'old pending bed keeps its historical readyAt');
eq(H.complete(ongoing,30_000),1,'old pending bed heals on its historical readyAt');
const healthy=state([patient('healthy',100)]);
assert.throws(()=>H.start(healthy,'healthy',0),/tous ses PV/);checks++;
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const game=fs.readFileSync(path.join(root,'js/game.js'),'utf8');
assert.match(html,/RPG · VERSION 15\.17/);checks++;
assert.match(html,/BELLYMON · V15\.17/);checks++;
assert.match(html,/selon les PV manquants/);checks++;
assert.match(game,/HOSPITAL\.healDurationMs\(hero\)/);checks++;
assert.doesNotMatch(game,/Soins commencés : 18 secondes/);checks++;
console.log('BELLYMON V15.17 : '+checks+' validations de l’hôpital à durée variable.');
